#!/usr/bin/env python3
from __future__ import annotations

import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    print("PyYAML required: pip install pyyaml", file=sys.stderr)
    sys.exit(1)

REPO_ROOT = Path(__file__).resolve().parent.parent
PROFILE = REPO_ROOT / "user" / "profile.yaml"
OUT = REPO_ROOT / "tools" / "pii_blocklist.txt"

if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))
from src.brain.atomic_io import atomic_write_text, read_regular_text  # noqa: E402


def collect_tokens(data: dict) -> list[str]:
    user = data.get("user", {})
    tokens: set[str] = set()

    def add(value: object) -> None:
        token = " ".join(str(value or "").split())
        if len(token) >= 3:
            tokens.add(token)

    for key in ("name", "full_name"):
        add(user.get(key))

    fam = data.get("family", {}) or user.get("family", {})
    if isinstance(fam, dict):
        partner = fam.get("partner") or {}
        for key in ("name", "full_name"):
            add(partner.get(key))
        for child in fam.get("children", []) or []:
            if isinstance(child, dict) and (n := child.get("name")):
                add(n)

    identifier_keys = {
        "account_id",
        "e164",
        "phone",
        "phone_number",
        "user_id",
        "username",
    }

    def walk(node, *, key: str = ""):
        if isinstance(node, dict):
            for child_key, value in node.items():
                walk(value, key=str(child_key).lower())
        elif isinstance(node, list):
            for v in node:
                walk(v, key=key)
        elif isinstance(node, (str, int)):
            value = str(node).strip()
            if "@" in value and "." in value:
                if not value.endswith(
                    ("@example.com", "@example.test", "@invoice.test")
                ):
                    add(value)
            elif key in identifier_keys:
                add(value)

    walk(data)

    return sorted(t for t in tokens if t)


def main() -> int:
    try:
        profile_text = read_regular_text(PROFILE)
    except OSError:
        print(f"{PROFILE} not found — nothing to do.", file=sys.stderr)
        return 1
    data = yaml.safe_load(profile_text)
    tokens = collect_tokens(data or {})
    lines = [
        "# Generated by tools/gen_pii_blocklist.py from user/profile.yaml.",
        "# Gitignored. Pre-commit `check-pii` blocks staged diffs containing these.",
        "# To add false-positive exceptions, delete the matching line.",
        "",
        *tokens,
        "",
    ]
    atomic_write_text(OUT, "\n".join(lines), mode=0o600)
    print(f"Wrote {len(tokens)} tokens to {OUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
